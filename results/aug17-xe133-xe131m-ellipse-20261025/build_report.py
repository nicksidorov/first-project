"""Rebuild the readable report from saved ordinary XeMat results; no fits."""
from pathlib import Path
import csv
import json

ROOT = Path(__file__).resolve().parent


def read(name):
    return json.loads((ROOT/name).read_text(encoding='utf-8'))


def number(value):
    return '—' if value in (None, '') else f'{float(value):.7g}'


def main():
    scenario, ellipses = read('scenario.json'), read('ellipses.json')
    metadata = scenario['metadata']
    with (ROOT/'concentrations.csv').open(encoding='utf-8-sig') as stream:
        rows = list(csv.DictReader(stream))
    quality = read('fit_diagnostics.json')
    lines = ['# XeMat: августовская проба и доверительные эллипсы Xe133–Xe131m', '',
        'Обычная обработка трёх исходных спектров неизменённым XeMat, детектор **221**, '
        'фиксированные ROI и фиксированные эффективности. Использованы исходные различные Rs/Rg для пробы и памяти. '
        'SAMPLE, GASBK и DETBK подогнаны совместно: 21 наблюдение и 17 параметров. '
        'Все четыре метода сошлись; повторного моделирования наблюдений нет.', '',
        '**Качество подгонки требует внимания:** χ²/ν = 11.5104 для свободного МНК и D/ν = 11.6948 '
        'для свободного ММП, ν = 4. Модель заметно расходится с наблюдениями относительно принятой '
        'статистической погрешности. Эллипсы ниже — номинальные 95%-е области в рамках этой модели; '
        'их фактическое 95%-е покрытие для реальных данных не проверено. Причина расхождения '
        'этим расчётом не установлена.', '',
        '## Исходные данные и условия', '',
        '| Роль | Файл | Начало измерения из #Acquisition | Реальное / живое время, s |',
        '|---|---|---|---:|']
    for role,key,meta in [('SAMPLE','sample_file','sample_temporal'),('GASBK','background_file','background_temporal'),('DETBK','detector_file','detector_temporal')]:
        t=metadata[meta]
        lines.append(f"| {role} | {scenario['input_files'][key]['file']} | {t['start_time']} | {t['real_time']} / {t['live_time']} |")
    t=metadata['time_parameters']
    lines += ['', 'Дата в имени SAMPLE — 17 августа; начало измерения в заголовке — **16 августа 2025 года, 17:20:58.1**. '
        'Временные поправки используют заголовок файла.', '',
        f"Объём ксенона: {metadata['xenon_volume_cm3']} cm³. Использованный эффективный объём воздуха "
        f"V₀ = V_Xe/0.087 = **{metadata['effective_air_volume_m3']:.12g} m³** — по обычной формуле программы. "
        f"Поле air_volume в SAMPLE ({metadata['sample_temporal']['air_volume']} m³) сохранено в метаданных и не подменяет V₀.", '',
        f"Пробоотбор t_a={t['t_a']} s; ожидание t_p={t['t_p']} s; интервал начал GASBK→SAMPLE τ={t['tau']} s. "
        f"ROI: {metadata['sample_roi_numbers']}; полные энергетические границы сохранены в scenario.json.", '',
        '## Фиксированные эффективности и branching', '',
        'Эффективности ε не включают branching; чувствительность I = ε × BR. '
        'Значения взяты из constants.py для детектора 221, а не из разделов #b-gEfficiency файлов.', '',
        '| Изотоп | ε SAMPLE | ε GASBK | Branching BR | ε × BR |',
        '|---|---:|---:|---:|---:|']
    for name,e_c,e_g in zip(metadata['efficiency_isotope_names'],metadata['sample_efficiencies'],metadata['gasbk_efficiencies']):
        br=scenario['branching'][name]
        lines.append(f'| {name} | {e_c:.6f} | {e_g:.6f} | {br:.4f} | {e_c*br:.9f} |')
    lines += ['| Rn222 | 0.300000 | 0.300000 | 0.3700 | 0.111000000 |', '',
        'Для радона сохранён прежний режим legacy с обычной поправкой на распад. '
        'Его первая физическая координата вспомогательная; атмосферную концентрацию радона по ней не приводим.', '',
        'Систематика в текущем обычном расчёте: δI = **0.001 = 0.1%** для каждого компонента '
        'и δV₀ = **0.001 = 0.1%**. Это фактические числа из constants.py. '
        'К полной ковариации добавлены принятые программой вклады чувствительностей и общего объёма. '
        'Неопределённость матриц R и возможные ошибки самой модели сюда не добавлялись.', '',
        '## Результаты обычного расчёта', '',
        'Все концентрации, σ, LC и MDC ниже — **mBq/m³**. σ означает одно стандартное отклонение, '
        'а не 95%-й интервал. Для ограниченных методов обычная ковариация не выдаётся: пропуск σ не означает нулевую погрешность. '
        'Решение об обнаружении в каждой семье методов основано на свободной оценке > LC, как в приложении.', '',
        '| Метод | Изотоп | Концентрация | σ stat | σ total | LC | MDC | Обнаружение |',
        '|---|---|---:|---:|---:|---:|---:|---|']
    for r in rows:
        lines.append('| '+ ' | '.join([r['method'],r['isotope'],number(r['concentration_mBq_m3']),
            number(r['sigma_stat_mBq_m3']),number(r['sigma_total_mBq_m3']),number(r['LC_mBq_m3']),
            number(r['MDC_mBq_m3']),'да' if r['detected_from_free_estimate']=='True' else 'нет'])+' |')
    lines += ['', '## Эллипсы Xe133–Xe131m', '',
        '![Nominal joint confidence regions](xe133_xe131m_ellipse.png)', '',
        'Горизонтальная ось — концентрация Xe133, вертикальная — Xe131m. '
        'Крест показывает оценённую пару концентраций. Сплошная граница использует статистическую '
        'ковариацию, пунктирная — полную с указанной выше систематикой. Обе панели имеют одинаковый масштаб. '
        'Показан увеличенный участок около оценок; начало координат за пределами рисунка.', '',
        'Пусть c=(a_V,Xe133, a_V,Xe131m). Область определяется условием', '',
        '`(c − c_hat)^T @ inv(K_pair) @ (c − c_hat) ≤ χ²(2; 0.95) = 5.9914645471`.', '',
        'K_pair — блок 2×2 ковариации концентраций, полученной из **полной** модели с памятью, '
        'радоном и DETBK. Остальные параметры оценивались совместно; их не считали известными '
        'при построении эллипса. Полуоси равны sqrt(5.99146 × собственное значение K_pair). '
        'Множитель 1.96 для одномерного интервала здесь не используется.', '',
        '| Метод | Ковариация | Центр Xe133 | Центр Xe131m | r | Большая / малая полуось, mBq/m³ |',
        '|---|---|---:|---:|---:|---:|']
    for e in ellipses:
        c=e['center_mBq_m3'];a=e['semi_axes_mBq_m3']
        lines.append(f"| {e['method']} | {e['uncertainty']} | {c[0]:.7f} | {c[1]:.7f} | {e['correlation']:.7f} | {a[0]:.7f} / {a[1]:.7f} |")
    lines += ['', 'Отрицательный наклон показывает взаимную компенсацию оценок: при большем Xe133 '
        'модель допускает меньший Xe131m, и наоборот. Статистическая корреляция около −0.43 '
        'практически одинакова у МНК и ММП. Это корреляция погрешностей оценок в данной модели, '
        'а не корреляция истинных концентраций в атмосфере.', '',
        'Для ММП использована обратная ожидаемая информация Фишера при fitted μ. Для МНК — '
        'ковариация существующего оценивателя с весами w=1/x при x>0, w=1 при x=0. '
        'Нормальная аппроксимация и веса по наблюдениям дают приближённые области. '
        'Ковариации не умножались на приведённый χ² или девианс. Эллипсы не использовались '
        'для изменения обычных LC/MDC и решений об обнаружении.', '',
        '## Сходимость и качество подгонки', '',
        '| Метод | Статистика | ν | Статистика / ν | Сходимость |',
        '|---|---:|---:|---:|---|']
    for q in quality:
        symbol='χ²' if q['statistic_name']=='chi2' else 'D'
        lines.append(f"| {q['method']} | {symbol} = {q['statistic']:.7f} | {q['degrees_of_freedom']} | {q['reduced_statistic']:.7f} | да |")
    lines += ['', 'Для ограниченных методов ν=4 — номинальная нормировка. '
        'Численная сходимость подтверждена во всех четырёх расчётах; высокие χ²/ν и D/ν '
        'относятся к согласованности модели с данными. Полные остатки по ROI и предупреждения '
        'сохранены в обычных TXT/JSON отчётах.', '',
        '## Файлы и воспроизведение', '',
        f"Версия ядра XeMat: `{scenario['production_commit']}`. Контрольные суммы входных PHD и "
        'неизменённого ядра находятся в scenario.json. Монте-Карло не запускалось; seed не нужен.', '',
        '- `result_wls.txt`, `result_nnls.txt`, `result_poisson.txt`, `result_poisson_nonnegative.txt` — обычный оформленный экспорт приложения; соответствующие JSON содержат полные результаты.',
        '- `concentrations.csv`, `fit_quality.csv`, `ellipses.json`, `measurement_arrays.npz` — числа, ковариации, модели и исходные ROI-отсчёты.',
        '- `xe133_xe131m_ellipse.pdf`, `xe133_xe131m_ellipse.png` — векторный PDF и PNG 300 dpi; `figures.tex` — английская подпись.',
        '- `inputs/`, `kernel_snapshot/`, `analyze_measurement.py` — воспроизведение обычного расчёта.',
        '- `plot_ellipse.py` и `build_report.py` — изменение оформления по сохранённым результатам без повторной подгонки.',
        '- `verification.json`, `figure_verification.json`, `checksums.json` — проверки чисел и артефактов.', '',
        'Для перестроения рисунка: `python plot_ellipse.py`. Для повторения обычного расчёта: '
        '`python analyze_measurement.py`. Зависимости указаны в requirements.txt.']
    (ROOT/'report.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')


if __name__ == '__main__':
    main()
